#!/usr/bin/env python3
"""Create-only stair tables of the stair carry `qualified-stair-carry-motion-v1/` (decision 1981). Data only.

The successor-format twin of `qualified-claw-stair-motion-v1/` (ADR 1229 increment 3) for content 12's rooted rows
71-84: the empty walk-off and back-up, and for wood (73-78) and stone (79-84) the approach, descent, ascent,
half-turn, retreat and back-up. For each row, in the frame of its start root: the root and heading per key, the deck
supporting each interval, the decks its proofs stood on, and the row's clip ordinal in its own image (source 6 or 7).

Nothing is chosen: every number is `stair-carry-v1/evidence/tables-v1.json`'s (`derive_stair_carry_tables.py`),
which cross-checks the loaded gaits and the half-turn against content 10's rows 53-55 key for key. The tick counts
are not here: DEC-050's paces (decision 1981 P-1981-3) are the bundle's authored connector rows. The claw tables
stay published and unchanged.

Wire `UGSTRM01`, version 1, exactly as the claw tables (little-endian):
- 32-byte header: magic, u32 version 1, s64 profile content revision 12, u32 program count, u32 key count,
  u32 deck count; then the 32-byte SHA-256 of the content-12 profile wire.
- programs: 12 x i32 each: row, rooted, key count, first key, deck count, first deck, end x/y/z, start yaw, end yaw,
  the clip ordinal in the row's own image.
- keys: 5 x i32 each: root x/y/z, heading, the deck index supporting the interval that starts at the key.
- decks: 6 x i32 each (half-open box). Footer `UGSTEND1`.

    python3 godot/data/underground/mole-worker/publish_stair_carry_motion.py
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import struct
import sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
OUTPUT = HERE / "qualified-stair-carry-motion-v1"
CONTENT = HERE / "qualified-stair-carry-v13"
TABLES = HERE / "stair-carry-v1/evidence/tables-v1.json"
CONTENT_REVISION = 12
ROWS = tuple(range(71, 85))


def require(value: bool, code: str) -> None:
    """Every refusal names the failed derivation fact."""
    if not value:
        raise ValueError("STAIR_CARRY_MOTION_" + code)


def sha(raw: bytes) -> str:
    """Lower-case hex SHA-256."""
    return hashlib.sha256(raw).hexdigest()


def programs(record: dict | None = None) -> tuple:
    """The fourteen programs, the profile wire and the input census (`record` replaces the tables file in tests)."""
    profile = (CONTENT / "mole-worker.ugprof").read_bytes()
    manifest = json.loads((CONTENT / "manifest.json").read_text())
    require(sha(profile) == manifest["wire_sha256"] and manifest["content_revision"] == CONTENT_REVISION,
            "CONTENT")
    record = json.loads(TABLES.read_text()) if record is None else record
    table = record["programs"]
    require(record["decision"] == "1981" and [p["row"] for p in table] == list(ROWS), "TABLE_CENSUS")
    for p in table:
        require(p["rooted"] == 1 and len(p["keys"]) >= 2 and p["keys"][0][:3] == [0, 0, 0] and
                p["end"] == p["keys"][-1][:3] and p["source"] in (6, 7) and p["clip"] >= 1, "PROGRAM_" + str(p["row"]))
        require(all(0 <= k[4] < len(p["decks"]) for k in p["keys"]), "DECK_INDEX_" + str(p["row"]))
    census = {str(TABLES.relative_to(ROOT)): sha(TABLES.read_bytes()),
              str((CONTENT / "mole-worker.ugprof").relative_to(ROOT)): sha(profile),
              str(Path(__file__).resolve().relative_to(ROOT)): sha(Path(__file__).read_bytes())}
    return table, profile, census


def serialize(table: list, profile: bytes) -> bytes:
    """The UGSTRM01 wire."""
    keys = sum(len(p["keys"]) for p in table)
    decks = sum(len(p["decks"]) for p in table)
    out = b"UGSTRM01" + struct.pack("<IqIII", 1, CONTENT_REVISION, len(table), keys, decks)
    out += hashlib.sha256(profile).digest()
    first_key = first_deck = 0
    for p in table:
        out += struct.pack("<12i", p["row"], p["rooted"], len(p["keys"]), first_key, len(p["decks"]), first_deck,
                           *p["end"], p["yaw"][0], p["yaw"][1], p["clip"])
        first_key += len(p["keys"])
        first_deck += len(p["decks"])
    for p in table:
        for key in p["keys"]:
            out += struct.pack("<5i", *key)
    for p in table:
        for deck in p["decks"]:
            require(all(deck[a] < deck[a + 3] for a in range(3)), "DECK_BOX")
            out += struct.pack("<6i", *deck)
    return out + b"UGSTEND1"


def accessor(wire: bytes, table: list) -> str:
    """The generated pin file a runtime owner reads at activation."""
    return "\n".join([
        "extends RefCounted",
        "## Generated by publish_stair_carry_motion.py (decision 1981). Do not edit. Data only, not active.",
        "",
        'const WIRE_PATH: String = "res://data/underground/mole-worker/qualified-stair-carry-motion-v1/stair-motion.ugstair"',
        'const WIRE_SHA: String = "%s"' % sha(wire),
        "const WIRE_BYTES: int = %d" % len(wire),
        "const CONTENT_REVISION: int = %d" % CONTENT_REVISION,
        "const PROGRAM_COUNT: int = %d" % len(table),
        "const KEY_COUNT: int = %d" % sum(len(p["keys"]) for p in table),
        "const DECK_COUNT: int = %d" % sum(len(p["decks"]) for p in table),
        "",
    ])


def build() -> dict:
    """Every output file, in memory."""
    table, profile, census = programs()
    wire = serialize(table, profile)
    manifest = {"schema": 1, "decision": ["1981", "1229"], "content_revision": CONTENT_REVISION,
                "wire_sha256": sha(wire), "wire_bytes": len(wire),
                "programs": [{"row": p["row"], "name": f'{p["group"]}.{p["name"]}', "source": p["source"],
                              "keys": len(p["keys"]), "decks": p["decks"], "end_u": p["end"], "yaw": list(p["yaw"]),
                              "clip": p["clip"]} for p in table],
                "inputs": census, "runtime_admitted": False}
    return {"stair-motion.ugstair": wire, "catalog_source.gd": accessor(wire, table).encode(),
            "manifest.json": (json.dumps(manifest, indent=2) + "\n").encode()}


def main() -> int:
    """Create the publication exactly once."""
    require(not OUTPUT.exists(), "OUTPUT_EXISTS")
    outputs = build()
    OUTPUT.mkdir()
    for name, raw in outputs.items():
        (OUTPUT / name).write_bytes(raw)
    print("published", OUTPUT.relative_to(ROOT), {n: sha(r)[:12] for n, r in outputs.items()})
    return 0


if __name__ == "__main__":
    sys.exit(main())
