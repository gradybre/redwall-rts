#!/usr/bin/env python3
"""Create-only stair tables of content 13 `qualified-earth-carry-motion-v1/` (decision 2042). Data only, not active.

The successor of `qualified-stair-carry-motion-v1/` (decision 1981) for content 13: its fourteen programs (rows
71-84) unchanged, then six earth programs, rows 90-95, which are the stone programs 79-84 with only their row id and
source (9) changed. The earth rows move the same body and the same solid along the same keys (P-2042-1 (a)), so
every root, heading, deck and clip ordinal is the stone program's own. Same `UGSTRM01` wire, version 1, at profile
content revision 13 and the content-13 wire's digest.

    python3 godot/data/underground/mole-worker/publish_earth_carry_motion.py
"""
from __future__ import annotations

import copy
import hashlib
import json
from pathlib import Path
import sys

import publish_claw_runtime as PUB7
import publish_stair_carry_motion as STAIRS

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
OUTPUT = HERE / "qualified-earth-carry-motion-v1"
CONTENT = HERE / "qualified-earth-carry-v14"
CONTENT_REVISION = 13
STONE_ROWS, EARTH_ROWS, EARTH_SOURCE = tuple(range(79, 85)), tuple(range(90, 96)), 9


def require(value: bool, code: str) -> None:
    """Every refusal names the failed derivation fact."""
    if not value:
        raise ValueError("EARTH_CARRY_MOTION_" + code)


def sha(raw: bytes) -> str:
    """Lower-case hex SHA-256."""
    return hashlib.sha256(raw).hexdigest()


def programs() -> tuple:
    """Content 12's fourteen programs then the six earth copies; the content-13 wire; the input census."""
    stairs, _, census = STAIRS.programs()
    profile = (CONTENT / "mole-worker.ugprof").read_bytes()
    manifest = json.loads((CONTENT / "manifest.json").read_text())
    require(sha(profile) == manifest["wire_sha256"] and manifest["content_revision"] == CONTENT_REVISION, "CONTENT")
    _, _, fields, _ = PUB7.parse(profile)
    require(len(fields) == 96 and all(fields[row][0] == EARTH_SOURCE and fields[row - 11][0] == 7 and
                                      fields[row][1:8] == fields[row - 11][1:8] and fields[row][9:14] ==
                                      fields[row - 11][9:14] and fields[row][15:18] == fields[row - 11][15:18]
                                      for row in EARTH_ROWS), "WIRE_ROWS")
    stone = [p for p in stairs if p["row"] in STONE_ROWS]
    require([p["row"] for p in stone] == list(STONE_ROWS) and all(p["source"] == 7 for p in stone), "STONE_PROGRAMS")
    earth = []
    for program, row in zip(stone, EARTH_ROWS):
        moved = copy.deepcopy(program)
        moved.update(row=row, source=EARTH_SOURCE, group="earth")
        earth.append(moved)
    census[str((CONTENT / "mole-worker.ugprof").relative_to(ROOT))] = sha(profile)
    census[str(Path(__file__).resolve().relative_to(ROOT))] = sha(Path(__file__).read_bytes())
    return stairs + earth, profile, census


def serialize(table: list, profile: bytes) -> bytes:
    """The UGSTRM01 wire at content revision 13 (decision 1981's serializer)."""
    saved, STAIRS.CONTENT_REVISION = STAIRS.CONTENT_REVISION, CONTENT_REVISION
    try:
        return STAIRS.serialize(table, profile)
    finally:
        STAIRS.CONTENT_REVISION = saved


def accessor(wire: bytes, table: list) -> str:
    """The generated pin file a runtime owner reads at activation."""
    return "\n".join([
        "extends RefCounted",
        "## Generated by publish_earth_carry_motion.py (decision 2042). Do not edit. Data only, not active.",
        "",
        'const WIRE_PATH: String = "res://data/underground/mole-worker/qualified-earth-carry-motion-v1/stair-motion.ugstair"',
        'const WIRE_SHA: String = "%s"' % sha(wire),
        "const WIRE_BYTES: int = %d" % len(wire),
        "const CONTENT_REVISION: int = %d" % CONTENT_REVISION,
        "const PROGRAM_COUNT: int = %d" % len(table),
        "const KEY_COUNT: int = %d" % sum(len(p["keys"]) for p in table),
        "const DECK_COUNT: int = %d" % sum(len(p["decks"]) for p in table),
        "",
    ])


def build() -> dict:
    """Every output file, in memory."""
    table, profile, census = programs()
    wire = serialize(table, profile)
    manifest = {"schema": 1, "decision": ["2042", "1981", "1229"], "content_revision": CONTENT_REVISION,
                "wire_sha256": sha(wire), "wire_bytes": len(wire),
                "programs": [{"row": p["row"], "name": f'{p["group"]}.{p["name"]}', "source": p["source"],
                              "keys": len(p["keys"]), "decks": p["decks"], "end_u": p["end"], "yaw": list(p["yaw"]),
                              "clip": p["clip"]} for p in table],
                "inputs": census, "runtime_admitted": False}
    return {"stair-motion.ugstair": wire, "catalog_source.gd": accessor(wire, table).encode(),
            "manifest.json": (json.dumps(manifest, indent=2) + "\n").encode()}


def main() -> int:
    """Create the publication exactly once."""
    require(not OUTPUT.exists(), "OUTPUT_EXISTS")
    outputs = build()
    OUTPUT.mkdir()
    for name, raw in outputs.items():
        (OUTPUT / name).write_bytes(raw)
    print("published", OUTPUT.relative_to(ROOT), {n: sha(r)[:12] for n, r in outputs.items()})
    return 0


if __name__ == "__main__":
    sys.exit(main())
